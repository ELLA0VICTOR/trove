const packageId = "0x" + "1".repeat(64),
  objectId = "0x" + "2".repeat(64);
function setup() {
  const store = new DemoStore(":memory:"),
    market = new MarketService(store);
  const parentKey = Ed25519Keypair.generate(),
    learnerKey = Ed25519Keypair.generate(),
    attestor = Ed25519Keypair.generate();
  const family = randomUUID(),
    parent: Member = {
      id: randomUUID(),
      family,
      username: "parent",
      role: "parent",
    },
    learner: Member = {
      ...parent,
      id: randomUUID(),
      username: "learner",
      role: "learner",
    };
  let submissions = 0;
  const submitted: string[] = [];
  const gateway = {
    network: "testnet",
    client: {
      executeTransaction: async (input: { transaction: Uint8Array }) => {
        submissions++;
        submitted.push(Buffer.from(input.transaction).toString("base64"));
        throw new Error("Response lost");
      },
    },
    receipt: async () => {
      throw new Error("Temporarily unknown");
    },
    object: async () => {
      throw new Error("Unexpected object read");
    },
  } as unknown as TatumSuiGateway;
  const chain = new ChainService(store, market, {
    packageId,
    fundingReady: true,
    sponsorKey: Ed25519Keypair.generate().getSecretKey(),
    attestorKey: attestor.getSecretKey(),
    gateway,
  });
  const bind = async () => {
    await store.db
      .prepare("INSERT INTO chain_wallets VALUES(?,?,?)")
      .run(family, "parent", parentKey.toSuiAddress());
    await store.db
      .prepare("INSERT INTO chain_wallets VALUES(?,?,?)")
      .run(family, "learner", learnerKey.toSuiAddress());
  };
  return {
    store,
    market,
    chain,
    gateway,
    parent,
    learner,
    parentKey,
    learnerKey,
    attestor,
    bind,
    submissions: () => submissions,
    submitted,
  };
}
test("wallet links require the correct member-scoped, expiring, single-use signed challenge", async () => {
  const { store, chain, parent, learner, parentKey, learnerKey } = setup();
  try {
    const challenge = await chain.challenge(parent, parentKey.toSuiAddress());
    await assert.rejects(
      async () => await chain.link(parent, challenge.id, "invalid-signature"),
    );
    const wrong = await learnerKey.signPersonalMessage(
      Buffer.from(challenge.message),
    );
    await assert.rejects(
      async () => await chain.link(parent, challenge.id, wrong.signature),
      /signature/,
    );
    const right = await parentKey.signPersonalMessage(
      Buffer.from(challenge.message),
    );
    await assert.rejects(
      async () => await chain.link(learner, challenge.id, right.signature),
      /expired/,
    );
    await chain.link(parent, challenge.id, right.signature);
    assert.equal(
      await chain.wallet(parent.family, "parent"),
      parentKey.toSuiAddress(),
    );
    await assert.rejects(
      async () => await chain.link(parent, challenge.id, right.signature),
      /expired/,
    );
    const same = await chain.challenge(learner, parentKey.toSuiAddress()),
      signed = await parentKey.signPersonalMessage(Buffer.from(same.message));
    await assert.rejects(
      async () => await chain.link(learner, same.id, signed.signature),
      /separate/,
    );
  } finally {
    await store.db.close();
  }
});
