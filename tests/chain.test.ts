test("quote expiry follows consensus time and refuses an excessive clock skew", async () => {
  const { store, chain, gateway } = setup();
  try {
    const consensus = Date.now() - 3000;
    gateway.object = async () =>
      ({
        object: {
          content: ClockBcs.serialize({
            id: "0x6",
            timestamp_ms: consensus,
          }).toBytes(),
        },
      }) as never;
    const expiry = await chain.quoteExpiry();
    assert.ok(expiry > Date.now());
    assert.ok(expiry < consensus + 120000);
    gateway.object = async () =>
      ({
        object: {
          content: ClockBcs.serialize({
            id: "0x6",
            timestamp_ms: Date.now() - 60000,
          }).toBytes(),
        },
      }) as never;
    await assert.rejects(() => chain.quoteExpiry(), /Sui clock/);
  } finally {
    await store.db.close();
  }
});
test("crash recovery resubmits only identical signed bytes and unknown outcomes never change balances", async () => {
  const { store, chain, parent, submitted, submissions } = setup();
  try {
    const id = randomUUID(),
      before = await store.get(parent.family);
    await store.db
      .prepare("INSERT INTO chain_intents VALUES(?,?,?,?,?,?,?,?,?,?,?)")
      .run(
        id,
        parent.family,
        parent.id,
        "policy",
        "{}",
        "AQID",
        "digest",
        "user-signature",
        "submitting",
        Date.now() + 120000,
        null,
      );
    // Include the persisted state exactly as if a process stopped after validation.
    await chain.reconcilePending();
    assert.equal(submissions(), 1);
    assert.deepEqual(submitted, ["AQID"]);
    assert.equal((await store.get(parent.family)).cash, before.cash);
    await chain.reconcilePending();
    assert.equal(submissions(), 1); // cooldown survives another worker cycle
    await store.db.prepare("UPDATE chain_dispatch SET next_at=0").run();
    await chain.reconcilePending();
    assert.equal(submissions(), 2);
    assert.equal(submitted[0], submitted[1]);
    assert.equal(
      (
        (await store.db
          .prepare("SELECT state FROM chain_intents WHERE id=?")
          .get(id)) as {
          state: string;
        }
      ).state,
      "submitting",
    );
  } finally {
    await store.db.close();
  }
});
