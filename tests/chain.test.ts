    state.policy.paused = true;
    await store.set(state);
    await store.db
      .prepare("INSERT INTO chain_accounts VALUES(?,?,?)")
      .run(parent.family, objectId, "created");
    const fundingId = randomUUID(),
      amount = "500000000";
    const intent = {
      id: randomUUID(),
      family: parent.family,
      member: parent.id,
      action: "fund",
      payload: JSON.stringify({
        id: fundingId,
        amount,
        sequence: state.sequence,
        portfolioId: state.portfolio.id,
      }),
      bytes: "AQID",
      digest: "funding-digest",
      signature: "signature",
      state: "pending",
      expires_at: Date.now() + 60000,
      error: null,
    };
    await store.db
      .prepare("INSERT INTO chain_intents VALUES(?,?,?,?,?,?,?,?,?,?,?)")
      .run(...Object.values(intent));
    const projected = structuredClone(state);
    applyFunding(projected, {
      id: fundingId,
      amount,
      recordedAt: new Date().toISOString(),
    });
    let wrongAmount = true,
      wrongSpending = false;
    const fundingOrigin = "0x" + "3".repeat(64);
    chain.config!.eventTypeOrigins = { Funded: fundingOrigin };
    let eventOrigin = "0x" + "4".repeat(64);
    gateway.receipt = async () =>
      ({
        state: "confirmed",
        transaction: {
          digest: intent.digest,
          timestampMs: String(Date.now()),
          events: [
            {
              packageId,
              module: "practice",
              eventType: `${eventOrigin}::practice::Funded`,
              bcs: FundedBcs.serialize({
                account: objectId,
                id: Array.from(
                  Buffer.from(fundingId.replaceAll("-", ""), "hex"),
                ),
                amount: wrongAmount ? "1" : amount,
                cash: projected.cash,
                sequence: String(projected.sequence),
              }).toBytes(),
            },
          ],
        },
      }) as never;
    gateway.object = async () =>
      ({
        object: {
          type: `${packageId}::practice::Account`,
          content: AccountBcs.serialize({
            id: objectId,
            guardian: parentKey.toSuiAddress(),
            learner: learnerKey.toSuiAddress(),
            attestor: Array.from(attestor.getPublicKey().toRawBytes()),
            cash: projected.cash,
            positions: state.holdings.map((holding) => ({
              symbol: Array.from(Buffer.from(holding.symbol)),
              units: holding.units,
              cost: holding.cost,
            })),
            per_trade: state.policy.perTrade,
            daily: state.policy.daily,
            paused: state.policy.paused,
            allowed: state.policy.allowed.map((symbol) =>
              Array.from(Buffer.from(symbol)),
            ),
            revision: state.policy.revision,
            sequence: projected.sequence,
            day_spent: wrongSpending ? "0" : state.daySpent,
            spend_day: Math.floor(Date.parse(state.spendDay) / 86400000),
            approval: [],
          }).toBytes(),
        },
      }) as never;
    await assert.rejects(
      () => chain.reconcile(intent),
      /funding receipt does not match/,
    );
    eventOrigin = fundingOrigin;
    await assert.rejects(
      () => chain.reconcile(intent),
      /funding receipt failed/,
    );
    wrongAmount = false;
    wrongSpending = true;
    await assert.rejects(
      () => chain.reconcile(intent),
      /funding receipt failed/,
    );
    wrongSpending = false;
    await chain.reconcile(intent);
    await chain.reconcile(intent);
